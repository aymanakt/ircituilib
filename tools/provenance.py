#!/usr/bin/env python3
"""provenance.py — the one place a generated artefact's provenance line is written.

WHY THIS FILE EXISTS

Every artefact this pipeline generates carries a line naming the tool that last
wrote it and when, and the verifier writes a second line into every artefact it
polices saying when it looked and what it found. That is an audit trail: the file
on disk answers "what produced this, and when was it last checked", without the
reader needing the log or the terminal that ran the tool.

THREE CONSUMERS, ONE FORMAT

tools/gen_ui.py, tools/gen_decl_types.py and tools/post_generation_verifier.py
all write these lines, and two of the three also have to READ past them: R23
compares the checked-in headers against what gen_decl_types emits now, which
carries a stamp from the current run -- so the comparison strips the lines first
or it would fail on every run. An emitter and a stripper that disagree about the
format is the failure mode this module exists to prevent, and it is why the
regexes below are the only copy.

THE STAMP RECORDS THE INVOCATION, NOT A CHANGE

Every run writes its line, whether or not the emitted body moved. That is
deliberate, and it is what the artefacts' sibling `src/version.c` does: its whole
purpose is to stamp the build it was made in. The consequence is that the
artefacts are no longer byte-reproducible -- §9 of IRCITUILIB_LAYOUT_GENERATION.md
compares them with the provenance stripped instead, and the two runs' stamps are
expected to differ.

WHAT IS NOT STAMPED

tools/validate_layout.py is a referee and owns no artefact, so it stamps nothing:
there is no file of its making to carry a line. It reports through stderr and its
exit status, which is where a validator's verdict belongs.
"""
from __future__ import annotations

import datetime
import getpass
import re
import socket

# The tools as they are named on the command line, which is what a reader of the
# artefact would type to reproduce it.
GEN_UI = "tools/gen_ui.py"
GEN_DECL_TYPES = "tools/gen_decl_types.py"
VERIFIER = "tools/post_generation_verifier.py"

# A generated line, anchored: the whole line is the stamp, so a comment that
# merely mentions one cannot be stripped by accident.
_GENERATED_RE = re.compile(r"^/\* generated by [^\n]*\*/\n", re.M)
_VERIFIED_RE = re.compile(r"^/\* verified by [^\n]*\*/\n?", re.M)

# Both kinds, for a reader that wants the body and not the trail.
_ANY_RE = re.compile(r"^/\* (?:generated|verified) by [^\n]*\*/\n?", re.M)


def _now() -> str:
    """Local time, to the second, with its own offset.

    ISO 8601 rather than `date`'s format, because this line is read by a person
    comparing two artefacts and by nothing else -- and an offset makes the two
    comparable without knowing which host wrote which."""
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def _who() -> str:
    """`user@host`, with the host cut at its first dot.

    The same shape src/version.c.sh stamps the build with, so one grep finds both
    stamps and neither has to be explained."""
    return f"{getpass.getuser()}@{socket.gethostname().split('.')[0]}"


def generated_line(tool: str) -> str:
    """The line a generator writes into the artefact it just emitted.

    `tool` is the command-line spelling -- `tools/gen_ui.py` -- because the line's
    job is to say what to run to get this file again."""
    return f"/* generated by {tool} at {_now()} {_who()} */"


def verified_line(tool: str, passed: bool) -> str:
    """The line the verifier writes into every artefact it policed.

    The verdict is on the line rather than left to the exit status: a stamp that
    said "verified" over an artefact whose verification failed would be worse than
    no stamp, and a failing run is still an invocation worth recording."""
    return f"/* verified by {tool} at {_now()} -- {'PASSED' if passed else 'FAILED'} */"


def strip(text: str) -> str:
    """`text` with every provenance line removed.

    This is what makes two artefacts from two runs comparable: everything else in
    them is deterministic (§9), so what remains after this is the body."""
    return _ANY_RE.sub("", text)


def with_verified(text: str, tool: str, passed: bool) -> str:
    """`text` carrying a verified line for this run, and no earlier one.

    One line, not a history: the artefact says when it was last checked, and a
    trail that grows a line per run would be a log inside a source file. The line
    sits directly under the generated one, so the two read as a pair -- what made
    this, then what last looked at it."""
    line = verified_line(tool, passed) + "\n"
    text = _VERIFIED_RE.sub("", text)
    m = _GENERATED_RE.search(text)
    # No generated line to sit under means this is not an artefact this pipeline
    # made; the line still goes in, at the top, rather than being dropped.
    return text[:m.end()] + line + text[m.end():] if m else line + text
